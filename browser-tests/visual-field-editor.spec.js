import {test,expect} from "@playwright/test";
test("visual field editor builds a reusable definition without hand-editing JSON",async({page})=>{
 await page.goto("/");
 await page.locator('[data-workspace-tab="analyze"]').click();
 await page.locator("#protocol-definition-builder > summary").click();
 await page.locator("#pd-id").fill("visual_demo");
 await page.locator("#pd-name").fill("Visual demo");
 await page.locator("#pd-length").fill("4");
 await expect(page.locator("#pd-byte-map button")).toHaveCount(4);
 await page.locator('#pd-byte-map button[data-offset="1"]').click();
 await expect(page.locator("#pd-field-start")).toHaveValue("1");
 await page.locator("#pd-field-name").fill("device");
 await page.locator("#pd-field-width").fill("2");
 await page.locator("#pd-field-apply").click();
 await expect(page.locator("#pd-status")).toContainText("Field added");
 await expect(page.locator("#pd-fields")).toHaveValue(/device/);
 await expect(page.locator('#pd-byte-map button[data-offset="1"]')).toHaveAttribute("title",/device/);
 await page.locator("#pd-field-select").selectOption("0");
 await page.locator("#pd-field-name").fill("device_id");
 await page.locator("#pd-field-apply").click();
 await expect(page.locator("#pd-fields")).toHaveValue(/device_id/);
 await page.locator("#pd-save").click();
 await expect(page.locator("#pd-status")).toContainText("Saved");
 await page.locator("#pd-field-select").selectOption("0");
 await page.locator("#pd-field-remove").click();
 await expect(page.locator("#pd-fields")).toHaveValue("[]");
 await page.locator("#pd-library").selectOption("visual_demo");
 await page.locator("#pd-load").click();
 await expect(page.locator("#pd-fields")).toHaveValue(/device_id/);
});
