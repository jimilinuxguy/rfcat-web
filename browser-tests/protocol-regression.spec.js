import {test,expect} from "@playwright/test";
test("M16 saves regression fixtures, blocks incompatible protocol edits and survives reload",async({page})=>{
 await page.goto("/");
 await page.locator('[data-workspace-tab="analyze"]').click();
 await page.locator("#protocol-definition-builder > summary").click();
 await page.locator("#pd-id").fill("m16_browser");
 await page.locator("#pd-name").fill("M16 Browser");
 await page.locator("#pd-length").fill("3");
 await page.locator("#pd-sync").fill("AA");
 await page.locator("#pd-fields").fill(JSON.stringify([{name:"counter",start:1,width:1,type:"uint"}]));
 await page.locator("#pd-save").click();
 await expect(page.locator("#pd-status")).toContainText("Saved");
 await page.locator("#pd-regression-id").fill("known-good");
 await page.locator("#pd-regression-hex").fill("AA0102");
 await page.locator("#pd-regression-add").click();
 await page.locator("#pd-regression-id").fill("known-bad");
 await page.locator("#pd-regression-hex").fill("BB0102");
 await page.locator("#pd-regression-match").selectOption("false");
 await page.locator("#pd-regression-add").click();
 await page.locator("#pd-regression-run").click();
 await expect(page.locator("#pd-status")).toContainText("Regression passed: 2 of 2");
 await page.locator("#pd-regression-save").click();
 await expect(page.locator("#pd-status")).toContainText("Saved 2 regression fixtures");
 await page.locator("#pd-sync").fill("BB");
 await page.locator("#pd-save").click();
 await expect(page.locator("#pd-status")).toContainText("Save blocked");
 await page.locator("#pd-sync").fill("AA");
 await page.locator("#pd-save").click();
 await expect(page.locator("#pd-status")).toContainText("Saved");
 await page.reload();
 await page.locator('[data-workspace-tab="analyze"]').click();
 await page.locator("#protocol-definition-builder > summary").click();
 await page.locator("#pd-library").selectOption("m16_browser");
 await page.locator("#pd-load").click();
 await expect(page.locator("#pd-regression-json")).toHaveValue(/known-good/);
 await page.locator("#pd-regression-run").click();
 await expect(page.locator("#pd-status")).toContainText("Regression passed: 2 of 2");
});
