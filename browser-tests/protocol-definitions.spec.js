import {test,expect} from "@playwright/test";
test("create, save, reload, validate and import a protocol definition offline",async({page})=>{
 await page.goto("/");
 await page.evaluate(async()=>{const {saveCaptureSession}=await import("./js/storage/capture-session-store.js");await saveCaptureSession({id:"m13-fixture",name:"M13 fixture",captures:[{hex:"AA0102"},{hex:"AA0203"},{hex:"BB0102"}]});});
 await page.locator('[data-workspace-tab="analyze"]').click();
 await page.locator("#protocol-definition-builder summary").click();
 await page.locator("#pd-id").fill("m13_test");
 await page.locator("#pd-name").fill("M13 test");
 await page.locator("#pd-length").fill("3");
 await page.locator("#pd-sync").fill("AA");
 await page.locator("#pd-fields").fill(JSON.stringify([{name:"counter",start:1,width:1,type:"uint"},{name:"value",start:2,width:1,type:"hex"}]));
 await page.locator("#pd-save").click();
 await expect(page.locator("#pd-status")).toContainText("Saved");
 await page.locator("#pd-library").selectOption("m13_test");
 await page.locator("#pd-fields").fill("[]");
 await page.locator("#pd-load").click();
 await expect(page.locator("#pd-fields")).toContainText("counter");
 await page.locator("#pd-session").selectOption("m13-fixture");
 await page.locator("#pd-validate").click();
 await expect(page.locator("#pd-status")).toContainText("2 of 3 captures matched");
 await page.locator("#pd-packet").fill("AA0102");
 await page.locator("#pd-decode").click();
 await expect(page.locator("#pd-output")).toContainText('"matched": true');
 const saved=await page.evaluate(async()=>{const {getProtocolDefinition}=await import("./js/storage/protocol-definition-store.js");return getProtocolDefinition("m13_test");});
 expect(saved.fields).toHaveLength(2);
 await page.reload();
 await page.locator('[data-workspace-tab="analyze"]').click();
 await page.locator("#protocol-definition-builder summary").click();
 await page.locator("#pd-library").selectOption("m13_test");
 await page.locator("#pd-load").click();
 await expect(page.locator("#pd-name")).toHaveValue("M13 test");
});
test("promoting annotations requires preview and explicit confirmation",async({page})=>{
 await page.goto("/");
 await page.evaluate(async()=>{const {saveCaptureSession}=await import("./js/storage/capture-session-store.js");await saveCaptureSession({id:"m13-promote",name:"M13 promotion",captures:[{hex:"AA0102"}],fieldAnnotations:{"3":[{name:"sequence",start:1,width:1,kind:"counter"}]}});});
 await page.locator('[data-workspace-tab="analyze"]').click();
 await page.locator("#protocol-definition-builder summary").click();
 await page.locator("#pd-id").fill("promoted");
 await page.locator("#pd-name").fill("Promoted");
 await page.locator("#pd-session").selectOption("m13-promote");
 await expect(page.locator("#pd-confirm")).toBeDisabled();
 await page.locator("#pd-promote").click();
 await expect(page.locator("#pd-preview")).toContainText("sequence");
 await expect(page.locator("#pd-confirm")).toBeEnabled();
 await page.locator("#pd-confirm").click();
 await expect(page.locator("#pd-fields")).toContainText('"type": "uint"');
 await expect(page.locator("#pd-status")).toContainText("not saved");
});
